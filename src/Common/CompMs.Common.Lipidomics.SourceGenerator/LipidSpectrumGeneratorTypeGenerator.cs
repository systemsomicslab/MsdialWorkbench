        "LSG001",
        "Ion rule skipped",
        "Ion '{0}' was skipped: {1}",
        "LipidSpectrumModel",
        DiagnosticSeverity.Warning,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor InvalidValueRule = new(
        "LSG002",
        "Unrecognized value",
        "<{0}> value '{1}' is not recognized; treated as {2}",
        "LipidSpectrumModel",
        DiagnosticSeverity.Warning,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor UnknownIonListRule = new(
        "LSG003",
        "Unknown ion list",
        "<{0}> is not a known ion list and is ignored",
        "LipidSpectrumModel",
        DiagnosticSeverity.Warning,
        isEnabledByDefault: true);

    private static void LoadElements(Context.RegisterHandle handle, XElement element)
    {
        var parser = new FormulaSentenceParser();
        foreach (var variable in element.Elements().Where(e => !_peakElements.Contains(e.Name.LocalName)))
        {
            if (variable.HasElements)
            {

            }
            var sub = variable.HasElements
                ? parser.Parse(variable.Name.LocalName, variable.ToString())
                : parser.Parse(variable.Name.LocalName, variable.Value);
            if (sub is not null)
            {
                handle.Register(sub);
            }
        }
    }

